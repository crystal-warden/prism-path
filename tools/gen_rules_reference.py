"""Regenerate the reference tables of docs/guides/writing-agent-rules.md from the code they describe.

The guide is written by hand except for the blocks between marker comments, which this tool owns. The field
table comes from prismpath/agent/fields.py and the reading domain `profile.KNOWN_CATEGORIES`, the required
fields from `fields.REQUIRED`, and the cause table from the cause registry (prismpath/kernel/causes.py), the
causes a rule names (`policy_source.RULE_CLASSES`). They cannot drift because the test rebuilds them.

    python tools/gen_rules_reference.py           rewrite the blocks in place
    python tools/gen_rules_reference.py --check   exit 1 when a committed block is out of date
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
GUIDE = os.path.join(ROOT, "docs", "guides", "writing-agent-rules.md")
NOTE = "(generated by tools/gen_rules_reference.py; do not edit by hand)"


def _cell(text):
    return str(text).replace("|", "\\|")


def fields_block():
    from prismpath.agent import fields
    lines = ["| field | kind | values | what it reads |", "|---|---|---|---|"]
    for name, kind, meaning in fields.FIELDS:
        values = ", ".join(f"`{value}`" for value in fields.values(name)) or ("true or false" if kind == "bool" else "a whole number")
        lines.append(f"| `{name}` | {kind} | {values} | {_cell(meaning)} |")
    return "\n".join(lines)


def required_block():
    from prismpath.agent import fields
    return "\n".join(f"* `{name}`, {why}" for name, why in fields.REQUIRED)


def causes_block():
    from prismpath.kernel import policy_source
    lines = ["| code | cause | meaning |", "|---|---|---|"]
    for code, name, _klass, description in policy_source.cause_rows():
        lines.append(f"| {code} | `{name}` | {_cell(description)} |")
    return "\n".join(lines)


BLOCKS = (("fields", fields_block), ("required", required_block), ("causes", causes_block))


def splice(text, name, block):
    begin, end = f"<!-- {name}:begin {NOTE} -->", f"<!-- {name}:end -->"
    if begin not in text or end not in text:
        raise SystemExit(f"{GUIDE} has no {name} markers")
    head, rest = text.split(begin, 1)
    _old, tail = rest.split(end, 1)
    return f"{head}{begin}\n{block}\n{end}{tail}"


def build(text):
    for name, make in BLOCKS:
        text = splice(text, name, make())
    return text


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when a block of the guide is out of date")
    args = parser.parse_args(argv)
    with open(GUIDE, encoding="utf-8") as handle:
        old = handle.read()
    new = build(old)
    if args.check:
        if new != old:
            print("docs/guides/writing-agent-rules.md is out of date. Run tools/gen_rules_reference.py", file=sys.stderr)
            return 1
        return 0
    with open(GUIDE, "w", encoding="utf-8") as handle:
        handle.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
