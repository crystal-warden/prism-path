"""Regenerate the route tables of docs/guides/mission-control-api.md from the console's `app.openapi()`.

The guide is written by hand except for the block between the two marker comments, which this tool
owns. The routes cannot drift because the block is rebuilt from the app: the full posture's schema for
every route, the read only posture's for which of them it mounts. A route's line is the first sentence of
its docstring, so a route with no docstring shows up here as an empty line and the check fails.

    python tools/gen_mission_control_guide.py           rewrite the block in place
    python tools/gen_mission_control_guide.py --check   exit 1 when the committed block is out of date
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GUIDE = os.path.join(ROOT, "docs", "guides", "mission-control-api.md")
BEGIN = "<!-- routes:begin (generated by tools/gen_mission_control_guide.py; do not edit by hand) -->"
END = "<!-- routes:end -->"

# Which interface a route belongs to, by the first of its tags that names one. The followed run's readers
# serve every interface, so they are listed once under their own heading.
GROUPS = (
    ("Authoring", "the process owner", ("authoring",)),
    ("Operating", "the operator", ("operating", "control", "quality")),
    ("Auditing", "the assessor", ("auditing",)),
    ("The followed run", "every interface", ("observe", "events", "pick")),
)


def _first_sentence(text):
    paragraph = " ".join((text or "").strip().split("\n\n")[0].split())
    cut = re.search(r"\.(\s|$)", paragraph)
    return (paragraph[:cut.start()] if cut else paragraph).replace("|", "\\|")


def _routes(schema):
    for path, operations in schema["paths"].items():
        for method, operation in operations.items():
            yield method.upper(), path, operation


def render(full_schema, read_only_schema):
    mounted = {(m, p) for m, p, _ in _routes(read_only_schema)}
    rows = {name: [] for name, _, _ in GROUPS}
    for method, path, operation in _routes(full_schema):
        tags = operation.get("tags", [])
        for name, _, wanted in GROUPS:
            if any(tag in wanted for tag in tags):
                posture = "both" if (method, path) in mounted else "full only"
                rows[name].append((path, method, posture, _first_sentence(operation.get("description", ""))))
                break
        else:
            raise SystemExit(f"{method} {path} has tags {tags}, which no group of the guide takes")
    out = []
    for name, who, _ in GROUPS:
        out.append(f"### {name} ({who})\n")
        out.append("| Method | Path | Posture | What it does |")
        out.append("|---|---|---|---|")
        for path, method, posture, text in sorted(rows[name]):
            out.append(f"| {method} | `{path}` | {posture} | {text} |")
        out.append("")
    total, kept = sum(len(v) for v in rows.values()), len(mounted)
    out.append(f"{total} routes in the full posture, {kept} in the read only posture. "
               "A `full only` route is one that changes something, and the schema marks it "
               '`"x-prismpath-capability": "write"`.')
    return "\n".join(out)


def build_block():
    sys.path.insert(0, ROOT)
    from prismpath.mission_control.app import create_app
    from prismpath.mission_control.session import Session
    full = create_app(read_only=False, session=Session.mint()).openapi()
    read_only = create_app(read_only=True, session=Session.mint()).openapi()
    return render(full, read_only)


def splice(text, block):
    head, sep, rest = text.partition(BEGIN)
    if not sep or END not in rest:
        raise SystemExit(f"{GUIDE} lacks the {BEGIN!r} and {END!r} markers")
    _, _, tail = rest.partition(END)
    return head + BEGIN + "\n\n" + block + "\n\n" + END + tail


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the guide's block is out of date")
    args = parser.parse_args(argv)
    with open(GUIDE, encoding="utf-8") as handle:
        old = handle.read()
    new = splice(old, build_block())
    if args.check:
        if new != old:
            print("docs/guides/mission-control-api.md is out of date; run tools/gen_mission_control_guide.py",
                  file=sys.stderr)
            return 1
        return 0
    with open(GUIDE, "w", encoding="utf-8") as handle:
        handle.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
