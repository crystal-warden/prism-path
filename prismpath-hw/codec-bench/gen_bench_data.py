#!/usr/bin/env python3
"""Generate bench_data.h: two workloads of symbol tuples + expected wire bytes from the
Python reference (zeckendorf.encode_stream -> packed.pack(bits, 8)). The firmware verifies
byte identity on-device BEFORE timing, so the published number is the cost of a verified codec."""
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "adapters" / "telemetry"))
import packed  # noqa: E402
import zeckendorf as z  # noqa: E402

random.seed(42)
N = 64


def gen(workload, lo_hi):
    rows = []
    for _ in range(N):
        ints = [random.randint(*lo_hi) for _ in range(4)]     # 4 fields, wire ints (symbol+1)
        wire = packed.pack(z.encode_stream(ints), 8)
        rows.append((ints, wire))
    return rows


typ = gen("typ", (1, 6))          # realistic: 3 to 6 cell fields
stress = gen("stress", (1, 1001))  # 1000 cell codebook stress

out = ["/* GENERATED by gen_bench_data.py from the Python reference. Do not edit. */",
       "#include <stdint.h>", f"#define BENCH_N {N}", "#define BENCH_FIELDS 4"]
for name, rows in (("TYP", typ), ("STRESS", stress)):
    out.append(f"static const uint16_t TBL {name}_SYMS[BENCH_N][BENCH_FIELDS] = {{")
    out += ["  {%s}," % ", ".join(map(str, ints)) for ints, _ in rows]
    out.append("};")
    maxlen = max(len(w) for _, w in rows)
    out.append(f"#define {name}_MAXWIRE {maxlen}")
    out.append(f"static const uint8_t TBL {name}_WIRE[BENCH_N][{maxlen}] = {{")
    out += ["  {%s}," % ", ".join(str(b) for b in w.ljust(maxlen, b'\x00')) for _, w in rows]
    out.append("};")
    out.append(f"static const uint8_t TBL {name}_WLEN[BENCH_N] = {{" +
               ", ".join(str(len(w)) for _, w in rows) + "};")
tot_typ = sum(len(w) for _, w in typ)
tot_st = sum(len(w) for _, w in stress)
out.append(f"/* typical: {tot_typ/N:.3f} B/event, stress: {tot_st/N:.3f} B/event */")
Path("bench_data.h").write_text("\n".join(out) + "\n")
print(f"typ {tot_typ/N:.3f} B/event, stress {tot_st/N:.3f} B/event")
