"""The monitor scenario's autonomy plan, and what the policy must decide with and without the monitor's blessing.

The autonomy app (`nos3/pp_autonomy`, the S3 app) proposes the plan one command a second after the ground starts it,
and the playbook as soon as it sees the payload report a fault. This plan is longer than S3's on purpose: the
scenario's ground has to act in the middle of it (silence the monitor, bring it back, inject the fault), and the plan
must still be running when each of those has had its effect.

Every steady proposal is a slew of 25 or 30 degrees in ground contact. By the rules of example.rules.md alone each
is allowed, so when one is escalated the only rule that can have done it is the monitor's.

`decide` is the outcome table as a function of the reading, written by hand from the rules and held by the tests to
the reference decision path (`prismpath.agent.policy`). The scenario holds the flight run to it.

    python -m integrations.cfs.monitor.plan      # writes the plan include the staged autonomy app compiles
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Dict, List, Tuple

from integrations.cfs.nos3.plan import ATTITUDE, PAYLOAD, Proposal, FAULT_COMMAND, FAULT_NODE, FAULT_RESPONSE, FAULT_STATUS

HERE = Path(__file__).resolve().parent

STEADY = 40
PLAN: List[Proposal] = [
    Proposal(1, "attitude: slew 20 deg in contact", ATTITUDE, 1, 20, 0),
    Proposal(2, "payload: start the observation", PAYLOAD, 1, 0, 0),
    Proposal(3, "attitude: slew 120 deg, past the 90 deg limit", ATTITUDE, 1, 120, 0),
    Proposal(4, "attitude: slew 40 deg in contact", ATTITUDE, 1, 40, 0),
] + [Proposal(5 + i, f"attitude: steady slew {25 + 5 * (i % 2)} deg in contact", ATTITUDE, 1, 25 + 5 * (i % 2), 0)
     for i in range(STEADY)]

# the monitor's property, the bound of the app's staleness check and the ground's two monitor commands
PROPERTY = "payload_quiet"
QUIET_SECONDS = 5            # spec/payload_quiet.c2po: no fault status in the last five seconds
STALE_SECS = 3               # the PrismPath app reads a verdict older than this as not ok
MONITOR_CMD_MID = 0x18C6
MONITOR_HALT_CC, MONITOR_RESUME_CC = 1, 2


def proposals() -> List[Proposal]:
    return PLAN + FAULT_RESPONSE


def by_tag() -> Dict[int, Proposal]:
    return {p.tag: p for p in proposals()}


def reading(p: Proposal, monitor_ok: bool) -> Dict[str, object]:
    return dict(cmd_class=p.cmd_class, ground_contact=bool(p.ground_contact), monitor_ok=monitor_ok,
                slew_deg=p.slew_deg, thrust_pct=p.thrust_pct)


def decide(p: Proposal, monitor_ok: bool) -> Tuple[str, int]:
    """(kind, registered cause) example.rules.md gives this proposal, written from the rules, top to bottom."""
    if p.cmd_class not in (1, 2, 3):
        return "refuse", 104                                   # agent:unclassifiable
    if (p.cmd_class == 2 and p.thrust_pct > 100) or (p.cmd_class == 1 and p.slew_deg > 90):
        return "refuse", 37                                    # route:contract-violation
    if not monitor_ok:
        return "escalate", 34                                  # route:needs-human, the monitor's rule
    if (p.cmd_class == 2 and p.thrust_pct > 50 or p.cmd_class == 1 and p.slew_deg > 45) and not p.ground_contact:
        return "escalate", 34
    return "allow", 0


def torque(p: Proposal) -> int:
    """The reaction wheel torque the vehicle app commands for an attitude proposal, in 10^-4 N m."""
    return p.slew_deg


def render() -> str:
    def rows(name: str, items: List[Proposal]) -> str:
        body = "".join(f"    {{{p.tag}, {p.cmd_class}, {p.ground_contact}, {p.slew_deg}, {p.thrust_pct}}}, /* {p.what} */\n"
                       for p in items)
        return f"static const PP_AUTONOMY_Proposal_t {name}[] = {{\n{body}}};\n"
    return ("/* SPDX-License-Identifier: Apache-2.0 */\n"
            "/* Copyright 2026 Crystal Warden Supply Chain Labs LLC */\n"
            "/* Generated by `python -m integrations.cfs.monitor.plan`. Do not edit. */\n"
            "/* {tag, cmd_class, ground_contact, slew_deg, thrust_pct} */\n"
            + rows("PP_AUTONOMY_Plan", PLAN) + rows("PP_AUTONOMY_FaultResponse", FAULT_RESPONSE)
            + f"#define PP_AUTONOMY_FAULT_STATUS {FAULT_STATUS}u\n")


def main(argv: List[str]) -> int:
    out = Path(argv[0]) if argv else HERE / "pp_autonomy_plan.inc"
    out.write_text(render())
    print(f"wrote {out}")
    return 0


__all__ = ["PLAN", "FAULT_RESPONSE", "FAULT_COMMAND", "FAULT_NODE", "FAULT_STATUS"]

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
