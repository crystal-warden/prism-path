"""Freeze cross-language vectors for RFC 6962 consistency proofs (section 2.1.2, verified as RFC 9162
section 2.1.4.2 says).

A consistency proof from m to n leaves shows that the tree over n leaves holds the tree over the first m
unchanged. The collector (`prismpath-ebpf/collector/`) puts one in every seal after the first a client
was sent, generated by `prismpath_rs::merkle::ProofWindow` from the leaves it keeps, and the console
checks it with `root_statement.verify_consistency`. This writes fixed leaf sequences and the proof between
many pairs of sizes, computed by RUNNING the Python batch reference (`root_statement.consistency_proof`)
and verified by the Python verifier before anything is written, and the transparency-dev reference
implementation's own consistency probes (`transparency_dev_consistency.json`, vendored under Apache-2.0)
with the verdict each must get.

    python prismpath/portable/gen_merkle_consistency_fixtures.py   ->  conformance/merkle_consistency.json

Regeneration is byte identical. `prismpath/tests/test_merkle_consistency.py` regenerates the file and
refuses drift; `prismpath-rs/tests/test_merkle_consistency.rs` replays its crate copy through the batch
`consistency_proof`, the streaming `ProofWindow` and `verify_consistency`.

Each set is `{"name", "leaves": [hex], "proofs": [{"old", "new", "old_root", "new_root", "proof"}]}`:

    rfc6962      the eight inputs of the Certificate Transparency reference tests, every 1 <= old <= new <= 8
    hash_leaves  33 leaves, each the SHA-256 of its index as 4 big-endian bytes, every 1 <= old <= new <= 33
    large        1000 such leaves, a few pairs either side of the powers of two up to 1000

Each probe is `{"name", "old", "new", "old_root", "new_root", "proof", "valid"}`, roots null where the
probe has none; `valid` is the reference implementation's verdict (not `wantErr`).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO))

from prismpath.ledgers import ledger_ots, root_statement as rs  # noqa: E402

OUT = HERE / "conformance" / "merkle_consistency.json"
PROBES = HERE / "transparency_dev_consistency.json"
FORMAT_VERSION = 1

RFC6962_INPUTS = ["", "00", "10", "2021", "3031", "40414243", "5051525354555657",
                  "606162636465666768696a6b6c6d6e6f"]
LARGE_PAIRS = [(1, 1000), (2, 1000), (255, 256), (256, 257), (255, 1000), (256, 1000), (257, 1000), (300, 777),
               (511, 512), (511, 1000), (512, 1000), (513, 1000), (640, 999), (999, 1000), (1000, 1000)]


def hash_leaves(count: int) -> list[str]:
    return [hashlib.sha256(index.to_bytes(4, "big")).hexdigest() for index in range(count)]


def case(leaves: list[str], old: int, new: int) -> dict:
    proof = rs.consistency_proof(leaves[:new], old)
    old_root, new_root = rs.merkle_root(leaves[:old]), rs.merkle_root(leaves[:new])
    assert rs.verify_consistency(old, new, old_root, new_root, proof), f"the reference rejects its own {old} -> {new}"
    return {"old": old, "new": new, "old_root": old_root, "new_root": new_root, "proof": proof}


def every_pair(leaves: list[str]) -> list[dict]:
    return [case(leaves, old, new) for new in range(1, len(leaves) + 1) for old in range(1, new + 1)]


def probes() -> list[dict]:
    vendored = json.loads(PROBES.read_text(encoding="utf-8"))
    out = []
    for probe in vendored["probes"]:
        entry = {"name": probe["file"], "old": probe["size1"], "new": probe["size2"], "old_root": probe["root1"],
                 "new_root": probe["root2"], "proof": probe["proof"], "valid": not probe["wantErr"]}
        verdict = rs.verify_consistency(entry["old"], entry["new"], entry["old_root"] or "", entry["new_root"] or "",
                                        entry["proof"])
        assert verdict is entry["valid"], f"the reference disagrees with transparency-dev on {probe['file']}"
        out.append(entry)
    return out


def build() -> dict:
    large = hash_leaves(1000)
    sets = [
        {"name": "rfc6962", "leaves": RFC6962_INPUTS, "proofs": every_pair(RFC6962_INPUTS)},
        {"name": "hash_leaves", "leaves": hash_leaves(33), "proofs": every_pair(hash_leaves(33))},
        {"name": "large", "leaves": large, "proofs": [case(large, old, new) for old, new in LARGE_PAIRS]},
    ]
    found = probes()
    vendored = json.loads(PROBES.read_text(encoding="utf-8"))
    return {
        "version": FORMAT_VERSION,
        "scheme": ledger_ots.MERKLE_SCHEME,
        "note": "RFC 6962 consistency proof vectors. proof is PROOF(old, D[new]) of RFC 6962 section 2.1.2 over "
        "the first new leaves, computed by the Python batch reference; every one verifies by RFC 9162 section "
        "2.1.4.2. A generator must give each proof byte for byte, a verifier must accept each and give every "
        "probe its valid verdict. The probes are transparency-dev/merkle's testdata/consistency at commit "
        f"{vendored['commit']} (Apache-2.0), hex for base64.",
        "counts": {"proofs": sum(len(entry["proofs"]) for entry in sets), "probes": len(found)},
        "sets": sets,
        "probes": found,
    }


def render() -> str:
    return json.dumps(build(), indent=1, sort_keys=True) + "\n"


def main() -> int:
    OUT.write_text(render())
    doc = json.loads(OUT.read_text())
    print(f"wrote {OUT.relative_to(REPO)}: {doc['counts']['proofs']} proofs, {doc['counts']['probes']} probes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
